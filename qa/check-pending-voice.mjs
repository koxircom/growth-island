import fs from 'node:fs';import ts from 'typescript';import vm from 'node:vm';import assert from 'node:assert/strict';import crypto from 'node:crypto';
const manifest=JSON.parse(fs.readFileSync(new URL('../PENDING-VOICE-PROVENANCE.json',import.meta.url),'utf8'));
assert.equal(manifest.state,'verified');
assert.equal(manifest.text,'后台语音正在合成中。');
assert.equal(manifest.engine,'qwen3-tts');
assert.equal(manifest.reference_sha256,'d2799d22d920afd7a349bd665f7c020c8513c891f12ee035944cc4c16c1b4944');
assert.equal(manifest.actual_playback_verified,true);
const playback=fs.readFileSync(new URL("./auto-voice-e2e-results.json",import.meta.url));
assert.equal(crypto.createHash("sha256").update(playback).digest("hex"),manifest.playback_report_sha256);
assert.equal(JSON.parse(playback).passed,true);
assert.equal(JSON.parse(playback).actual_native_audio_starts,2);
assert.equal(JSON.parse(playback).actual_native_audio_ends,2);
assert.ok(/^\/audio\/[a-zA-Z0-9_/-]+\.wav$/.test(manifest.url));
const wav=fs.readFileSync(new URL('../public'+manifest.url,import.meta.url));
assert.equal(crypto.createHash('sha256').update(wav).digest('hex'),manifest.sha256);
const source=fs.readFileSync(new URL('../lib/habit-voice-pending.ts',import.meta.url),'utf8');
const output=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const exports={};vm.runInNewContext(output,{exports},{timeout:1000});
assert.equal(exports.HABIT_VOICE_PENDING_TEXT,manifest.text);
assert.notEqual(exports.PENDING_HABIT_VOICE_RECORDING,null);
assert.equal(JSON.stringify(exports.PENDING_HABIT_VOICE_RECORDING),JSON.stringify({url:manifest.url,sha256:manifest.sha256,engine:manifest.engine,referenceSha256:manifest.reference_sha256}));
